package org.basaltmc.auth

import dev.whyoleg.cryptography.CryptographyProvider
import dev.whyoleg.cryptography.DelicateCryptographyApi
import dev.whyoleg.cryptography.algorithms.RSA
import dev.whyoleg.cryptography.algorithms.SHA1
import kotlin.test.Test
import kotlin.test.assertContentEquals
import kotlin.test.assertEquals
import kotlin.test.assertTrue

private fun hexToBytes(hex: String): ByteArray =
    ByteArray(hex.length / 2) { i -> hex.substring(i * 2, i * 2 + 2).toInt(16).toByte() }

class SessionKeyPairTest {
    @Test
    fun publicKeyDerIsWellFormedX509() {
        val keyPair = SessionKeyPair.generate()
        // A DER SubjectPublicKeyInfo sequence always starts with tag 0x30 (SEQUENCE).
        assertTrue(keyPair.publicKeyDer.isNotEmpty())
        assertEquals(0x30, keyPair.publicKeyDer[0].toInt())
    }

    @Test
    @OptIn(DelicateCryptographyApi::class)
    fun decryptsWhatAClientWouldEncryptFromTheAdvertisedDer() {
        val server = SessionKeyPair.generate()

        // Mirrors the client side of the handshake: decode the DER bytes received over the wire
        // (exactly what `Crypt.byteToPublicKey` does) and RSA-PKCS1-encrypt with it.
        val rsa = CryptographyProvider.Default.get(RSA.PKCS1)
        val clientPublicKey =
            rsa
                .publicKeyDecoder(
                    SHA1,
                ).decodeFromByteArrayBlocking(RSA.PublicKey.Format.DER, server.publicKeyDer)
        val sharedSecret = ByteArray(16) { it.toByte() }
        val encryptedSecret = clientPublicKey.encryptor().encryptBlocking(sharedSecret)

        assertContentEquals(sharedSecret, server.decrypt(encryptedSecret))
    }

    @Test
    fun sessionHashMatchesJdkGoldenVector() {
        // Golden vector generated by running the real `Crypt.digestData`-equivalent (SHA-1 over
        // serverId + secretKey.getEncoded() + publicKey.getEncoded()) plus `BigInteger.toString(16)`
        // on a JDK, with placeholder byte content standing in for the real key material.
        val hash =
            MinecraftCrypt.sessionHash(
                serverId = "",
                secretKey = "shared-secret-bytes".encodeToByteArray(),
                publicKeyDer = "public-key-bytes".encodeToByteArray(),
            )
        assertEquals("-7fc249fa02def4925027b6d62186cf0ede08cbc8", hash)
    }
}
