[[nodiscard]] Chunk groundChunk(std::int32_t chunkX, std::int32_t chunkZ, std::string_view surface, bool water) {
    Chunk chunk{chunkX, chunkZ};
    for (std::int32_t x = 0; x < 16; ++x) {
        for (std::int32_t z = 0; z < 16; ++z) {
            for (std::int32_t y = -64; y < 70; ++y) {
                chunk.setBlockStateId(x, y, z, registry::blocks::stone().stateId);
            }
            chunk.setBlockStateId(x, 70, z, stateIdOf(surface));
            if (water) {
                for (std::int32_t y = 71; y <= 72; ++y) {
                    chunk.setBlockStateId(x, y, z, registry::blocks::water().stateId);
                }
            }
        }
    }
    return chunk;
}

[[nodiscard]] std::int64_t checksumOf(const Chunk& chunk) {
    std::uint64_t checksum = 14695981039346656037ULL;
    for (std::int32_t y = 60; y <= 140; ++y) {
        for (std::int32_t z = 0; z < 16; ++z) {
            for (std::int32_t x = 0; x < 16; ++x) {
                checksum =
                    (checksum ^ static_cast<std::uint64_t>(static_cast<std::int64_t>(chunk.blockStateId(x, y, z)))) *
                    1099511628211ULL;
            }
        }
    }
    return static_cast<std::int64_t>(checksum);
}

struct Run {
    std::int32_t attempts = 0;
    std::size_t deferred = 0;
    std::int64_t checksum = 0;
    std::string origins;
};

[[nodiscard]] Run run(std::string_view name, std::string biome, std::string_view surface, bool water,
                      std::int32_t count) {
    Run result;
    std::uint64_t checksum = 14695981039346656037ULL;
    for (std::int32_t index = 0; index < count; ++index) {
        Chunk chunk = groundChunk(index * 5 - 30, index * -3 + 12, surface, water);
        const testsupport::FixedBiomeEnvironment environment{biome};
        treePatchDecoration::decorateFeature(
            chunk, 4242LL + index, environment, name, [&result](std::string_view, const DecorationPos& position) {
                ++result.attempts;
                result.origins += std::to_string(position.x) + ":" + std::to_string(position.y) + ":" +
                                  std::to_string(position.z) + " ";
            });
        checksum = (checksum ^ static_cast<std::uint64_t>(checksumOf(chunk))) * 1099511628211ULL;
        result.deferred += chunk.takeGeneratedBlockWrites().size();
    }
    result.checksum = static_cast<std::int64_t>(checksum);
    return result;
}

