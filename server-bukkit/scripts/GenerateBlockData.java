import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.lang.reflect.Type;
import java.lang.reflect.TypeVariable;
import java.lang.reflect.ParameterizedType;
import java.lang.reflect.WildcardType;
import java.lang.reflect.GenericArrayType;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeSet;
import org.bukkit.Material;
import org.bukkit.block.data.BlockData;

public final class GenerateBlockData {
    private GenerateBlockData() {}

    public static void main(String[] args) throws Exception {
        Path out = Path.of(args[0], "org", "bukkit", "craftbukkit", "block", "data");
        Files.createDirectories(out.resolve("generated"));
        TreeSet<Class<?>> interfaces = new TreeSet<>((a, b) -> a.getName().compareTo(b.getName()));
        for (Material material : Material.values()) {
            Class<?> data = material.data;
            if (data != null && data != BlockData.class && BlockData.class.isAssignableFrom(data) && data.isInterface()) {
                interfaces.add(data);
            }
        }
        List<String> names = new ArrayList<>();
        for (Class<?> type : interfaces) {
            String name = "Craft" + type.getSimpleName();
            names.add(type.getCanonicalName() + "|" + name);
            Files.writeString(out.resolve("generated").resolve(name + ".java"), wrapper(type, name));
        }
        StringBuilder table = new StringBuilder();
        table.append("package org.bukkit.craftbukkit.block.data;\n\n");
        table.append("import java.util.HashMap;\nimport java.util.Map;\nimport java.util.function.Function;\n");
        table.append("import org.basaltmc.bukkit.BasaltBlockData;\nimport org.basaltmc.bukkit.Registries;\n");
        table.append("import org.bukkit.block.data.BlockData;\n\n");
        table.append("/** Generated by server-bukkit/scripts/GenerateBlockData.java: do not edit. */\n");
        table.append("final class CraftBlockDataTypes {\n");
        table.append("    private static final Map<Class<?>, Function<BlockData, CraftBlockData>> kMakers = makers();\n\n");
        table.append("    private CraftBlockDataTypes() {}\n\n");
        table.append("    static CraftBlockData make(BlockData inner) {\n");
        table.append("        Class<?> face = Registries.materialOfState(BasaltBlockData.stateOf(inner)).data;\n");
        table.append("        Function<BlockData, CraftBlockData> maker = kMakers.get(face);\n");
        table.append("        return maker == null ? new CraftBlockData(inner) : maker.apply(inner);\n    }\n\n");
        table.append("    private static Map<Class<?>, Function<BlockData, CraftBlockData>> makers() {\n");
        table.append("        Map<Class<?>, Function<BlockData, CraftBlockData>> makers = new HashMap<>();\n");
        for (String entry : names) {
            String[] parts = entry.split("\\|");
            table.append("        makers.put(").append(parts[0]).append(".class, org.bukkit.craftbukkit.block.data.generated.")
                .append(parts[1]).append("::new);\n");
        }
        table.append("        return makers;\n    }\n}\n");
        Files.writeString(out.resolve("CraftBlockDataTypes.java"), table.toString());
    }

    private static String wrapper(Class<?> type, String name) {
        Map<String, Method> chosen = new LinkedHashMap<>();
        List<Method> methods = new ArrayList<>(List.of(type.getMethods()));
        methods.sort((a, b) -> a.toGenericString().compareTo(b.toGenericString()));
        for (Method method : methods) {
            if (Modifier.isStatic(method.getModifiers()) || declaredByBlockData(method)) {
                continue;
            }
            StringBuilder key = new StringBuilder(method.getName()).append('(');
            for (Class<?> parameter : method.getParameterTypes()) {
                key.append(parameter.getName()).append(',');
            }
            Method existing = chosen.get(key.toString());
            if (existing == null || existing.getReturnType().isAssignableFrom(method.getReturnType())) {
                chosen.put(key.toString(), method);
            }
        }
        StringBuilder source = new StringBuilder();
        source.append("package org.bukkit.craftbukkit.block.data.generated;\n\n");
        source.append("import org.bukkit.block.data.BlockData;\nimport org.bukkit.craftbukkit.block.data.CraftBlockData;\n\n");
        source.append("/** Generated by server-bukkit/scripts/GenerateBlockData.java: do not edit. */\n");
        source.append("@SuppressWarnings({\"rawtypes\", \"unchecked\", \"deprecation\", \"removal\"})\n");
        source.append("public final class ").append(name).append(" extends CraftBlockData implements ")
            .append(type.getCanonicalName()).append(" {\n");
        source.append("    public ").append(name).append("(BlockData inner) {\n        super(inner);\n    }\n\n");
        for (Method method : chosen.values()) {
            boolean erased = method.getDeclaringClass().getTypeParameters().length > 0;
            if (method.isDefault() && !overridesBlockData(method)) {
                continue;
            }
            source.append("    @Override\n    public ");
            source.append(typeName(method.getGenericReturnType())).append(' ').append(method.getName()).append('(');
            Type[] parameters = method.getGenericParameterTypes();
            for (int index = 0; index < parameters.length; index++) {
                if (index > 0) {
                    source.append(", ");
                }
                source.append(typeName(parameters[index])).append(" a").append(index);
            }
            source.append(')');
            Class<?>[] thrown = method.getExceptionTypes();
            for (int index = 0; index < thrown.length; index++) {
                source.append(index == 0 ? " throws " : ", ").append(thrown[index].getCanonicalName());
            }
            source.append(" {\n        ");
            if (method.getReturnType() != void.class) {
                source.append("return ");
            }
            source.append("((").append(type.getCanonicalName()).append(") inner()).").append(method.getName()).append('(');
            for (int index = 0; index < parameters.length; index++) {
                if (index > 0) {
                    source.append(", ");
                }
                source.append('a').append(index);
            }
            source.append(");\n    }\n\n");
        }
        source.append("}\n");
        return source.toString();
    }

    private static boolean declaredByBlockData(Method method) {
        try {
            BlockData.class.getMethod(method.getName(), method.getParameterTypes());
            return true;
        } catch (NoSuchMethodException e) {
            return false;
        }
    }

    private static boolean overridesBlockData(Method method) {
        return false;
    }

    private static String typeName(Type type) {
        if (type instanceof Class<?> raw) {
            return raw.getCanonicalName();
        }
        if (type instanceof ParameterizedType parameterized) {
            StringBuilder out = new StringBuilder(((Class<?>) parameterized.getRawType()).getCanonicalName()).append('<');
            Type[] arguments = parameterized.getActualTypeArguments();
            for (int index = 0; index < arguments.length; index++) {
                if (index > 0) {
                    out.append(", ");
                }
                out.append(typeName(arguments[index]));
            }
            return out.append('>').toString();
        }
        if (type instanceof TypeVariable<?> variable) {
            return variable.getName();
        }
        if (type instanceof WildcardType wildcard) {
            if (wildcard.getLowerBounds().length > 0) {
                return "? super " + typeName(wildcard.getLowerBounds()[0]);
            }
            Type[] upper = wildcard.getUpperBounds();
            return upper.length == 0 || upper[0] == Object.class ? "?" : "? extends " + typeName(upper[0]);
        }
        if (type instanceof GenericArrayType array) {
            return typeName(array.getGenericComponentType()) + "[]";
        }
        return type.getTypeName();
    }
}
