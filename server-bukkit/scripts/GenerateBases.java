import java.lang.reflect.GenericArrayType;
import java.lang.reflect.Method;
import java.lang.reflect.ParameterizedType;
import java.lang.reflect.Type;
import java.lang.reflect.TypeVariable;
import java.lang.reflect.WildcardType;
import java.lang.reflect.Modifier;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

public final class GenerateBases {
    private GenerateBases() {}

    public static void main(String[] args) throws Exception {
        Path out = Path.of(args[1], "org", "basaltmc", "bukkit", "gen");
        Files.createDirectories(out);
        for (String line : Files.readAllLines(Path.of(args[0]))) {
            line = line.strip();
            if (line.isEmpty() || line.startsWith("#")) {
                continue;
            }
            String[] words = line.split("\\s+");
            Class<?> type = Class.forName(words[0], false, GenerateBases.class.getClassLoader());
            Files.writeString(out.resolve(baseName(type) + ".java"), generate(type, words.length > 1 ? words[1] : null));
        }
    }

    private static String baseName(Class<?> type) {
        return type.getName().substring(type.getName().lastIndexOf('.') + 1).replace("$", "") + "Base";
    }

    private static boolean moreSpecific(Class<?> candidate, Class<?> than) {
        return than.isAssignableFrom(candidate) && candidate != than;
    }

    private static String generate(Class<?> type, String parent) {
        Map<String, Method> chosen = new LinkedHashMap<>();
        List<Method> methods = new ArrayList<>(List.of(type.getMethods()));
        methods.sort((a, b) -> a.toGenericString().compareTo(b.toGenericString()));
        for (Method method : methods) {
            if (!Modifier.isAbstract(method.getModifiers()) || Modifier.isStatic(method.getModifiers())) {
                continue;
            }
            StringBuilder key = new StringBuilder(method.getName()).append('(');
            for (Class<?> parameter : method.getParameterTypes()) {
                key.append(parameter.getName()).append(',');
            }
            Method existing = chosen.get(key.toString());
            if (existing == null || moreSpecific(method.getReturnType(), existing.getReturnType())) {
                chosen.put(key.toString(), method);
            }
        }
        // A default method in one interface can be re-declared abstract in another: drop what a default satisfies.
        for (Method method : type.getMethods()) {
            if (!method.isDefault()) {
                continue;
            }
            StringBuilder key = new StringBuilder(method.getName()).append('(');
            for (Class<?> parameter : method.getParameterTypes()) {
                key.append(parameter.getName()).append(',');
            }
            Method existing = chosen.get(key.toString());
            if (existing != null && existing.getDeclaringClass().isAssignableFrom(method.getDeclaringClass())
                && existing.getReturnType() == method.getReturnType()) {
                chosen.remove(key.toString());
            }
        }
        StringBuilder source = new StringBuilder();
        source.append("package org.basaltmc.bukkit.gen;\n\n");
        source.append("import org.basaltmc.bukkit.Unsupported;\n\n");
        source.append("/** Generated by server-bukkit/scripts/GenerateBases.java: do not edit. */\n");
        source.append("@SuppressWarnings({\"rawtypes\", \"unchecked\", \"deprecation\", \"removal\"})\n");
        source.append("public abstract class ").append(baseName(type)).append(parent == null ? "" : " extends " + parent)
            .append(" implements ")
            .append(type.getCanonicalName()).append(" {\n");
        for (Method method : chosen.values()) {
            boolean erased = method.getDeclaringClass().getTypeParameters().length > 0;
            source.append("    @Override\n    public ");
            if (!erased && method.getTypeParameters().length > 0) {
                source.append('<');
                TypeVariable<Method>[] variables = method.getTypeParameters();
                for (int index = 0; index < variables.length; index++) {
                    if (index > 0) {
                        source.append(", ");
                    }
                    source.append(variables[index].getName());
                    Type[] bounds = variables[index].getBounds();
                    if (!(bounds.length == 1 && bounds[0] == Object.class)) {
                        source.append(" extends ");
                        for (int bound = 0; bound < bounds.length; bound++) {
                            if (bound > 0) {
                                source.append(" & ");
                            }
                            source.append(typeName(bounds[bound]));
                        }
                    }
                }
                source.append("> ");
            }
            source.append(erased ? name(method.getReturnType()) : typeName(method.getGenericReturnType())).append(' ')
                .append(method.getName()).append('(');
            Type[] parameters = erased ? method.getParameterTypes() : method.getGenericParameterTypes();
            for (int index = 0; index < parameters.length; index++) {
                if (index > 0) {
                    source.append(", ");
                }
                source.append(erased ? name((Class<?>) parameters[index]) : typeName(parameters[index])).append(" a").append(index);
            }
            source.append(')');
            Class<?>[] thrown = method.getExceptionTypes();
            for (int index = 0; index < thrown.length; index++) {
                source.append(index == 0 ? " throws " : ", ").append(name(thrown[index]));
            }
            source.append(" {\n        throw Unsupported.hit(\"").append(type.getSimpleName()).append('#')
                .append(method.getName()).append("\");\n    }\n\n");
        }
        source.append("}\n");
        return source.toString();
    }

    private static String name(Class<?> type) {
        return type.getCanonicalName();
    }

    private static String typeName(Type type) {
        if (type instanceof Class<?> raw) {
            return raw.getCanonicalName();
        }
        if (type instanceof ParameterizedType parameterized) {
            StringBuilder out = new StringBuilder(((Class<?>) parameterized.getRawType()).getCanonicalName()).append('<');
            Type[] arguments = parameterized.getActualTypeArguments();
            for (int index = 0; index < arguments.length; index++) {
                if (index > 0) {
                    out.append(", ");
                }
                out.append(typeName(arguments[index]));
            }
            return out.append('>').toString();
        }
        if (type instanceof TypeVariable<?> variable) {
            return variable.getName();
        }
        if (type instanceof WildcardType wildcard) {
            if (wildcard.getLowerBounds().length > 0) {
                return "? super " + typeName(wildcard.getLowerBounds()[0]);
            }
            Type[] upper = wildcard.getUpperBounds();
            return upper.length == 0 || upper[0] == Object.class ? "?" : "? extends " + typeName(upper[0]);
        }
        if (type instanceof GenericArrayType array) {
            return typeName(array.getGenericComponentType()) + "[]";
        }
        return type.getTypeName();
    }
}
