public class DiscFragmentItem extends Item {
    public DiscFragmentItem(Item.Properties properties) {
        super(properties);
    }

    @Override
    public void appendHoverText(ItemStack itemStack, Item.TooltipContext context, TooltipDisplay display, Consumer<Component> builder, TooltipFlag tooltipFlag) {
        builder.accept(getDisplayName().withStyle(net.minecraft.ChatFormatting.GRAY));
    }

    public MutableComponent getDisplayName() {
        return Component.translatable(getDescriptionId() + ".desc");
    }
}
