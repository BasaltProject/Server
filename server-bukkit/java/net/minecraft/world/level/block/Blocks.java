    private static Block copperNamed(String id) {
        return named("minecraft:" + id);
    }

    private static WeatheringCopperCollection<Block> copper(String base) {
        boolean block = base.equals("copper_block");
        String[] states = {"", "exposed_", "weathered_", "oxidized_"};
        String[] ids = new String[4];
        for (int i = 0; i < 4; i++) {
            ids[i] = block ? (i == 0 ? "copper_block" : states[i] + "copper") : states[i] + base;
        }
        return new WeatheringCopperCollection<>(
            new WeatheringCopperCollection.ByState<>(copperNamed(ids[0]), copperNamed(ids[1]), copperNamed(ids[2]),
                copperNamed(ids[3])),
            new WeatheringCopperCollection.ByState<>(copperNamed("waxed_" + ids[0]), copperNamed("waxed_" + ids[1]),
                copperNamed("waxed_" + ids[2]), copperNamed("waxed_" + ids[3])));
    }
