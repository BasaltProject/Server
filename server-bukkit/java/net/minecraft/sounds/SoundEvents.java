    private static java.util.Map<String, SoundEvent> load() {
        java.util.Map<String, SoundEvent> map = new java.util.HashMap<>();
        try (java.io.InputStream in = SoundEvents.class.getResourceAsStream("/sound_events.txt")) {
            if (in == null) {
                return map;
            }
            for (String line : new String(in.readAllBytes(), java.nio.charset.StandardCharsets.UTF_8).split("\\R")) {
                String id = line.trim();
                if (id.isEmpty()) {
                    continue;
                }
                SoundEvent event = SoundEvent.createVariableRangeEvent(net.minecraft.resources.Identifier.withDefaultNamespace(id));
                String full = id.replace('.', '_').toUpperCase(java.util.Locale.ROOT);
                kById.put(id, event);
                map.putIfAbsent(full, event);
                int dot = id.indexOf('.');
                if (dot > 0) {
                    map.putIfAbsent(id.substring(dot + 1).replace('.', '_').toUpperCase(java.util.Locale.ROOT), event);
                }
            }
        } catch (java.io.IOException e) {
            throw new java.io.UncheckedIOException(e);
        }
        return map;
    }

    public static SoundEvent byId(String id) {
        return kById.get(id);
    }

    private static Holder.Reference<SoundEvent> ref(String field) {
        SoundEvent event = kByName.get(field);
        if (event == null) {
            event = SoundEvent.createVariableRangeEvent(net.minecraft.resources.Identifier.withDefaultNamespace(
                field.toLowerCase(java.util.Locale.ROOT).replaceFirst("_", ".")));
        }
        return new Holder.Reference<SoundEvent>((net.minecraft.core.Registry<SoundEvent>) null,
            (net.minecraft.resources.ResourceKey<SoundEvent>) (Object) net.minecraft.resources.ResourceKey.create(
                (net.minecraft.resources.ResourceKey) net.minecraft.core.registries.Registries.SOUND_EVENT, event.location()), event);
    }

